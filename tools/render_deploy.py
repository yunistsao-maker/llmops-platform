#!/usr/bin/env python3
"""Render deployment files from deploy/components.yaml (the single description of how each component runs).

Writes (K8S = --k8s-out, default deploy/k8s when that directory exists; skipped otherwise):
  K8S/base/<component>.yaml        ServiceAccount + Deployment/CronJob + Service + NetworkPolicies
  K8S/base/kustomization.yaml
  K8S/jobs/<name>.yaml             one-off Jobs (db-migrate, dataset imports) for scripts (apply.sh)
  K8S/extras/<component>.yaml      local-only components (mock-llm)
  K8S/testjobs/                    with --argocd: test-cluster-only hook Jobs (bucket-init)
  K8S/components.json              secret keys, gateway models, workloads (for make_secrets.py / gw_keys.py)
  deploy/compose/docker-compose.components.yml
  docs/onprem-handoff.md           the generated part between the BEGIN/END markers

--argocd: Job workloads with an `argocd` hook in the spec also go into base/ (or testjobs/ when test_only) as Argo CD
hooks, and the shared resources (ConfigMap, ServiceAccounts, NetworkPolicies) get an earlier sync wave, so that a
migration runs after its ServiceAccount and settings exist and before the new version rolls out.

Usage: python3 tools/render_deploy.py [--check] [--k8s-out DIR] [--argocd]
Needs PyYAML.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "deploy" / "components.yaml"
PART_OF = "llmops"
HEADER = "# Generated by tools/render_deploy.py from deploy/components.yaml. Do not edit by hand.\n"

# What each `uses` entry means: secret keys it adds, pod label it sets, and where traffic may go.
USES = {
    "postgres": {"secrets": ["DATABASE_URL"], "label": "postgres"},
    "s3": {"secrets": ["S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY"], "label": "s3"},
    "gateway": {"secrets": ["LLM_GATEWAY_KEY"], "label": "gateway"},
    "gateway-admin": {"secrets": ["LITELLM_MASTER_KEY"], "label": "gateway"},   # key-provisioner only
    "internet": {"secrets": [], "label": "internet"},
    "oidc": {"secrets": [], "label": "oidc"},   # verifies user tokens: fetches the IdP's keys (JWKS)
}
# Shared services a label lets a pod reach (inside the namespace): label -> (service pods, port)
PEERS = {"postgres": ("postgres", 5432), "s3": ("object-store", 7070), "gateway": ("llm-gateway", 4000)}
KIND_PORT = {"service": 8080, "worker": 8081}


class Dumper(yaml.SafeDumper):
    """Block style, keep key order, no aliases."""

    def ignore_aliases(self, data):  # noqa: D401
        return True

    def increase_indent(self, flow=False, indentless=False):  # indent list items under their key
        return super().increase_indent(flow, False)


def _str_presenter(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


Dumper.add_representer(str, _str_presenter)


def dump_docs(docs: list[dict]) -> str:
    return HEADER + "".join("---\n" + yaml.dump(d, Dumper=Dumper, sort_keys=False, width=120) for d in docs)


def labels(component: str, workload: str) -> dict:
    return {"app.kubernetes.io/name": workload, "app.kubernetes.io/component": component,
            "app.kubernetes.io/part-of": PART_OF}


def gateway_key_names(comp: dict) -> list[str]:
    """Env names that receive the component's gateway virtual key (most use LLM_GATEWAY_KEY)."""
    return comp.get("gateway_key_names", ["LLM_GATEWAY_KEY"]) if "gateway" in comp.get("uses", []) else []


def secret_keys(comp: dict) -> list[str]:
    keys: list[str] = []
    for u in comp.get("uses", []):
        keys += gateway_key_names(comp) if u == "gateway" else USES[u]["secrets"]
    keys += comp.get("secrets", [])
    return list(dict.fromkeys(keys))


def resources(spec: dict | None, defaults: dict) -> dict:
    r = {**defaults, **(spec or {})}
    return {"requests": {"cpu": r["cpu"], "memory": r["memory"]}, "limits": {"memory": r["memory_limit"]}}


def env_list(*maps: dict) -> list[dict]:
    merged: dict = {}
    for m in maps:
        merged.update(m or {})
    return [{"name": k, "value": str(v)} for k, v in merged.items()]


def pod_spec(name: str, cname: str, comp: dict, wl: dict, spec: dict, restart: str | None = None) -> dict:
    kind = wl["kind"]
    run_as = comp.get("run_as", 10001)
    image = comp.get("image", f"llmops/{cname}") + ":" + spec["defaults"]["tag"]
    container: dict = {"name": name, "image": image, "imagePullPolicy": "IfNotPresent"}
    if wl.get("command"):
        container["command"] = wl["command"]
    if wl.get("args"):
        container["args"] = [str(a) for a in wl["args"]]
    port = wl.get("port", KIND_PORT.get(kind))
    if kind == "service":
        container["ports"] = [{"name": "http", "containerPort": port}]
    elif kind == "worker":
        container["ports"] = [{"name": "health", "containerPort": port}]
    env_from = [{"configMapRef": {"name": "llmops-common"}}]
    if secret_keys(comp) or comp.get("optional_secrets"):
        env_from.append({"secretRef": {"name": f"llmops-{cname}"}})
    if "internet" in comp.get("uses", []):   # HTTPS_PROXY / NO_PROXY, only where outbound traffic is expected
        env_from.append({"configMapRef": {"name": "llmops-proxy", "optional": True}})
    if comp.get("cloud_identity"):            # AWS_REGION, Roles Anywhere ARNs, Azure / GCP identity settings
        env_from.append({"configMapRef": {"name": "llmops-cloud", "optional": True}})
    container["envFrom"] = env_from
    std_env = {}
    if kind == "service" and not (wl.get("own_port_env") or comp.get("own_port_env")):
        std_env["PORT"] = port
    if kind == "worker":
        std_env["HEALTH_PORT"] = port
    env = env_list(std_env, comp.get("env"), wl.get("env"))
    if env:
        container["env"] = env
    probes = wl.get("probes", {})
    if kind in ("service", "worker"):
        pname = "http" if kind == "service" else "health"
        container["startupProbe"] = {"httpGet": {"path": probes.get("liveness", "/healthz"), "port": pname},
                                     "periodSeconds": 5, "failureThreshold": probes.get("startup_failures", 24)}
        container["livenessProbe"] = {"httpGet": {"path": probes.get("liveness", "/healthz"), "port": pname},
                                      "periodSeconds": 20, "timeoutSeconds": 5, "failureThreshold": 3}
        container["readinessProbe"] = {"httpGet": {"path": probes.get("readiness", "/readyz"), "port": pname},
                                       "periodSeconds": 10, "timeoutSeconds": 5, "failureThreshold": 3}
    container["resources"] = resources(wl.get("resources"), spec["defaults"]["resources"])
    container["securityContext"] = {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True,
                                    "capabilities": {"drop": ["ALL"]}}
    mounts = [{"name": "tmp", "mountPath": "/tmp"}]
    volumes = [{"name": "tmp", "emptyDir": {"sizeLimit": wl.get("tmp_size", "256Mi")}}]
    for m in comp.get("mounts", []):
        mounts.append({"name": m["name"], "mountPath": m["path"], "readOnly": True})
        if "configmap" in m:
            vol = {"name": m["name"], "configMap": {"name": m["configmap"], "optional": bool(m.get("optional"))}}
        else:
            vol = {"name": m["name"], "secret": {"secretName": m["secret"], "optional": bool(m.get("optional"))}}
        volumes.append(vol)
    container["volumeMounts"] = mounts
    pod = {
        "serviceAccountName": cname,
        "automountServiceAccountToken": bool(comp.get("kube_api")),
        "securityContext": {"runAsNonRoot": True, "runAsUser": run_as, "runAsGroup": run_as, "fsGroup": run_as,
                            "seccompProfile": {"type": "RuntimeDefault"}},
        "terminationGracePeriodSeconds": 30,
        "containers": [container],
        "volumes": volumes,
    }
    if restart:
        pod["restartPolicy"] = restart
    return pod


def pod_labels(cname: str, wname: str, comp: dict) -> dict:
    lab = labels(cname, wname)
    for u in comp.get("uses", []):
        lab[f"llmops.io/{USES[u]['label']}"] = "true"
    return lab


SHARED_WAVE = "-10"   # with --argocd: ConfigMap, ServiceAccounts and NetworkPolicies before hooks and workloads


def hook_annotations(wl: dict) -> dict:
    h = wl.get("argocd") or {}
    ann = {"argocd.argoproj.io/hook": h.get("hook", "Sync"),
           "argocd.argoproj.io/hook-delete-policy": h.get("delete_policy", "BeforeHookCreation")}
    if h.get("wave") is not None:
        ann["argocd.argoproj.io/sync-wave"] = str(h["wave"])
    return ann


def with_wave(doc: dict, wave: str) -> dict:
    doc.setdefault("metadata", {}).setdefault("annotations", {})["argocd.argoproj.io/sync-wave"] = wave
    return doc


def workload_docs(cname: str, comp: dict, wl: dict, spec: dict) -> list[dict]:
    name, kind = wl["name"], wl["kind"]
    meta = {"name": name, "labels": labels(cname, name)}
    tmpl_meta = {"labels": pod_labels(cname, name, comp)}
    docs: list[dict] = []
    if kind in ("service", "worker"):
        docs.append({
            "apiVersion": "apps/v1", "kind": "Deployment", "metadata": meta,
            "spec": {"replicas": wl.get("replicas", 1), "revisionHistoryLimit": 3,
                     "selector": {"matchLabels": {"app.kubernetes.io/name": name}},
                     "template": {"metadata": tmpl_meta, "spec": pod_spec(name, cname, comp, wl, spec)}}})
        if kind == "service":
            port = wl.get("port", 8080)
            docs.append({"apiVersion": "v1", "kind": "Service", "metadata": meta,
                         "spec": {"selector": {"app.kubernetes.io/name": name},
                                  "ports": [{"name": "http", "port": port, "targetPort": "http"}]}})
    elif kind == "cronjob":
        docs.append({
            "apiVersion": "batch/v1", "kind": "CronJob", "metadata": meta,
            "spec": {"schedule": wl["schedule"], "timeZone": wl.get("timezone", "Asia/Taipei"),
                     "concurrencyPolicy": "Forbid", "startingDeadlineSeconds": 3600,
                     "successfulJobsHistoryLimit": 3, "failedJobsHistoryLimit": 5,
                     "jobTemplate": {"spec": {
                         "backoffLimit": wl.get("retries", 0),
                         "activeDeadlineSeconds": wl.get("deadline_seconds", 3600),
                         "ttlSecondsAfterFinished": 7 * 86400,
                         "template": {"metadata": tmpl_meta,
                                      "spec": pod_spec(name, cname, comp, wl, spec, restart="Never")}}}}})
    elif kind == "job":
        docs.append({
            "apiVersion": "batch/v1", "kind": "Job", "metadata": meta,
            "spec": {"backoffLimit": wl.get("retries", 2), "activeDeadlineSeconds": wl.get("deadline_seconds", 900),
                     "ttlSecondsAfterFinished": 86400,
                     "template": {"metadata": tmpl_meta,
                                  "spec": pod_spec(name, cname, comp, wl, spec, restart="Never")}}})
    else:
        raise SystemExit(f"{cname}/{name}: unknown kind {kind}")
    return docs


def policy(name: str, selector: dict, ingress=None, egress=None) -> dict:
    types, spec = [], {"podSelector": {"matchLabels": selector}}
    if ingress is not None:
        types.append("Ingress")
        spec["ingress"] = ingress
    if egress is not None:
        types.append("Egress")
        spec["egress"] = egress
    spec["policyTypes"] = types
    return {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
            "metadata": {"name": name, "labels": {"app.kubernetes.io/part-of": PART_OF}}, "spec": spec}


def service_policies(cname: str, comp: dict, wl: dict, spec: dict) -> list[dict]:
    """Callers listed in `callers` may reach this service (ingress here, egress on their side)."""
    name, port = wl["name"], wl.get("port", 8080)
    callers = wl.get("callers", comp.get("callers", []))
    if callers == "any":
        return [policy(f"{name}-ingress", {"app.kubernetes.io/name": name}, ingress=[{"ports": [{"port": port}]}])]
    if not callers:
        return []
    by_name = workloads_by_name(spec)
    peers = [{"podSelector": {"matchLabels": {"app.kubernetes.io/name": c}}} for c in callers if c in by_name]
    docs = [policy(f"{name}-ingress", {"app.kubernetes.io/name": name},
                   ingress=[{"from": peers, "ports": [{"port": port}]}])]
    for c in callers:
        if c in by_name:
            docs.append(policy(f"{c}-to-{name}", {"app.kubernetes.io/name": c},
                               egress=[{"to": [{"podSelector": {"matchLabels": {"app.kubernetes.io/name": name}}}],
                                        "ports": [{"port": port}]}]))
    return docs


def workloads_by_name(spec: dict) -> dict:
    out = {}
    for cname, comp in spec["components"].items():
        for wl in comp["workloads"]:
            out[wl["name"]] = (cname, wl)
    return out


def common_docs(spec: dict) -> list[dict]:
    docs = [{"apiVersion": "v1", "kind": "ConfigMap",
             "metadata": {"name": "llmops-common", "labels": {"app.kubernetes.io/part-of": PART_OF}},
             "data": {k: str(v) for k, v in spec["common"].items()}}]
    everyone = {"app.kubernetes.io/part-of": PART_OF}
    docs.append(policy("default-deny", {}, ingress=[], egress=[]))
    docs[-1]["spec"]["podSelector"] = {}
    docs.append(policy("allow-dns", everyone, egress=[{
        "to": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "kube-system"}},
                "podSelector": {"matchLabels": {"k8s-app": "kube-dns"}}}],
        "ports": [{"port": 53, "protocol": "UDP"}, {"port": 53, "protocol": "TCP"}]}]))
    # Shared services inside the namespace: the label on the client pod opens both directions.
    for label, (peer_name, port) in PEERS.items():
        peer = {"app.kubernetes.io/name": peer_name}
        docs.append(policy(f"{label}-clients-egress", {f"llmops.io/{label}": "true"},
                           egress=[{"to": [{"podSelector": {"matchLabels": peer}}], "ports": [{"port": port}]}]))
        docs.append(policy(f"{peer_name}-ingress", peer,
                           ingress=[{"from": [{"podSelector": {"matchLabels": {f"llmops.io/{label}": "true"}}}],
                                     "ports": [{"port": port}]}]))
    docs.append(policy("internet-egress", {"llmops.io/internet": "true"}, egress=[{
        "to": [{"ipBlock": {"cidr": "0.0.0.0/0", "except": spec["internet_except"]}}],
        "ports": [{"port": 443}, {"port": 80}]}]))
    return docs


def render(spec: dict, k8s_out: Path | None, argocd: bool = False) -> dict[Path, str]:
    out: dict[Path, str] = {}
    if k8s_out is not None:
        out.update(render_k8s(spec, k8s_out, argocd))
    out[ROOT / "deploy/compose/docker-compose.components.yml"] = render_compose(spec)
    handoff = ROOT / "docs/onprem-handoff.md"
    out[handoff] = render_handoff(spec, handoff.read_text(encoding="utf-8") if handoff.exists() else "")
    return out


def kustomization(resources: list[str]) -> str:
    return HEADER + yaml.dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
                               "resources": resources}, Dumper=Dumper, sort_keys=False)


def render_k8s(spec: dict, k8s: Path, argocd: bool) -> dict[Path, str]:
    out: dict[Path, str] = {}
    base, jobs, extras, testjobs = k8s / "base", k8s / "jobs", k8s / "extras", k8s / "testjobs"
    base_files = ["common.yaml"]
    common = common_docs(spec)
    out[base / "common.yaml"] = dump_docs([with_wave(d, SHARED_WAVE) for d in common] if argocd else common)
    test_files: list[str] = []
    for cname, comp in spec["components"].items():
        sa = {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": cname, "labels": labels(cname, cname)},
              "automountServiceAccountToken": bool(comp.get("kube_api"))}
        docs: list[dict] = [with_wave(sa, SHARED_WAVE) if argocd else sa]
        job_docs: list[dict] = []
        for wl in comp["workloads"]:
            if wl["kind"] == "job":
                plain = workload_docs(cname, comp, wl, spec)
                job_docs += plain
                if argocd and wl.get("argocd") and comp.get("profile") != "local":
                    hooked = workload_docs(cname, comp, wl, spec)
                    for d in hooked:
                        d["metadata"]["annotations"] = hook_annotations(wl)
                    if wl.get("test_only"):
                        out[testjobs / f"{wl['name']}.yaml"] = dump_docs(hooked)
                        test_files.append(f"{wl['name']}.yaml")
                    else:
                        docs += hooked
                continue
            docs += workload_docs(cname, comp, wl, spec)
            if wl["kind"] == "service":
                docs += [with_wave(d, SHARED_WAVE) if argocd else d for d in service_policies(cname, comp, wl, spec)]
        docs += comp.get("extra_k8s", [])
        if comp.get("profile") == "local":
            out[extras / f"{cname}.yaml"] = dump_docs(docs + job_docs)
            continue
        out[base / f"{cname}.yaml"] = dump_docs(docs)
        base_files.append(f"{cname}.yaml")
        for d in job_docs:
            out[jobs / f"{d['metadata']['name']}.yaml"] = dump_docs([d])
    extra_files = sorted(p.name for p in out if p.parent == extras)
    if extra_files:
        out[extras / "kustomization.yaml"] = kustomization(extra_files)
    if test_files:
        out[testjobs / "kustomization.yaml"] = kustomization(sorted(test_files))
    out[base / "kustomization.yaml"] = kustomization(base_files)
    out[k8s / "components.json"] = render_index(spec)
    return out


def render_compose(spec: dict) -> str:
    services: dict = {}
    local = spec.get("compose", {})
    for cname, comp in spec["components"].items():
        if comp.get("compose") is False:
            continue
        for wl in comp["workloads"]:
            if wl.get("compose") is False:
                continue
            env = {k: v for k, v in local.get("env", {}).items()}
            gw_names = set(gateway_key_names(comp))
            for key in secret_keys(comp):
                if key in gw_names and "LLM_GATEWAY_KEY" in local.get("secrets", {}):
                    env[key] = local["secrets"]["LLM_GATEWAY_KEY"]   # local: one key for everyone
                elif key in local.get("secrets", {}):
                    env[key] = local["secrets"][key]
            for k, v in {**(comp.get("env") or {}), **(wl.get("env") or {}),
                         **(comp.get("compose_env") or {}), **(wl.get("compose_env") or {})}.items():
                env[k] = str(v)
            svc: dict = {"image": comp.get("compose_image") or comp.get("image", f"llmops/{cname}") + ":${TAG:-dev}"}
            args = wl.get("compose_args", wl.get("args"))
            if args:
                svc["command"] = [str(a) for a in args]
            svc["environment"] = env
            dep_spec = wl["compose_depends_on"] if "compose_depends_on" in wl else local.get("depends_on", {})
            deps = {d: {"condition": c} for d, c in dep_spec.items()}
            if deps:
                svc["depends_on"] = deps
            if wl["kind"] in ("cronjob", "job"):
                svc["profiles"] = ["jobs"]
                svc["restart"] = "no"
            else:
                svc["restart"] = "unless-stopped"
            if wl.get("compose_ports"):
                svc["ports"] = wl["compose_ports"]
            vols = (comp.get("compose_volumes") or []) + (wl.get("compose_volumes") or [])
            if vols:
                svc["volumes"] = vols
            svc.update({"read_only": True, "tmpfs": ["/tmp"], "security_opt": ["no-new-privileges:true"],
                        "cap_drop": ["ALL"]})
            services[wl["name"]] = svc
    return HEADER + "# Used with docker-compose.yml: docker compose -f docker-compose.yml -f docker-compose.components.yml\n" \
        + yaml.dump({"services": services}, Dumper=Dumper, sort_keys=False, width=120)


def render_index(spec: dict) -> str:
    """Machine-readable summary for the shell tools (make-secrets.sh, gw-keys.sh): no PyYAML needed there."""
    import json
    idx = {}
    for cname, comp in spec["components"].items():
        idx[cname] = {"profile": comp.get("profile", "base"), "secret_keys": secret_keys(comp),
                      "optional_secrets": comp.get("optional_secrets", []),
                      "gateway_models": comp.get("gateway_models", []),
                      "gateway_key_names": gateway_key_names(comp),
                      "gateway_budget": comp.get("gateway_budget"),
                      "workloads": {w["name"]: w["kind"] for w in comp["workloads"]}}
    return json.dumps(idx, indent=2, ensure_ascii=False) + "\n"


BEGIN, END = "<!-- BEGIN generated: tools/render_deploy.py -->", "<!-- END generated -->"


def render_handoff(spec: dict, current: str) -> str:
    lines = [BEGIN, "", "| Component | Runs as | Command | Port / schedule | Secret keys (`llmops-<component>`) | Talks to |",
             "|---|---|---|---|---|---|"]
    for cname, comp in spec["components"].items():
        if comp.get("profile") == "local":
            continue
        for wl in comp["workloads"]:
            kind = wl["kind"]
            what = {"service": "Deployment + Service", "worker": "Deployment (worker)",
                    "cronjob": "CronJob", "job": "Job (run on demand)"}[kind]
            if kind == "service":
                where = f"{wl.get('port', 8080)} (`/healthz`, `/readyz`)" if not wl.get("probes") else \
                    f"{wl.get('port')} (`{wl['probes'].get('liveness')}`, `{wl['probes'].get('readiness')}`)"
            elif kind == "worker":
                where = f"health {wl.get('port', 8081)}"
            elif kind == "cronjob":
                where = f"`{wl['schedule']}` {wl.get('timezone', 'Asia/Taipei')}"
            else:
                where = "-"
            cmd = " ".join(str(a) for a in (wl.get("args") or [])) or "(image default)"
            keys = ", ".join(f"`{k}`" for k in secret_keys(comp)) or "-"
            talks = ", ".join(comp.get("uses", [])) or "-"
            extra = comp.get("talks_to")
            if extra:
                talks = talks + ", " + extra if talks != "-" else extra
            lines.append(f"| {wl['name']} | {what} | `{cmd}` | {where} | {keys} | {talks} |")
    lines += ["", "Optional secret keys: " + "; ".join(
        f"{c}: " + ", ".join(f"`{k}`" for k in comp["optional_secrets"])
        for c, comp in spec["components"].items() if comp.get("optional_secrets")), "", END]
    block = "\n".join(lines)
    if BEGIN in current and END in current:
        pre, rest = current.split(BEGIN, 1)
        post = rest.split(END, 1)[1]
        return pre + block + post
    return current + ("\n\n" if current else "") + block + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if any file is out of date (CI)")
    ap.add_argument("--k8s-out", type=Path, help="directory for base/, jobs/, extras/, testjobs/, components.json")
    ap.add_argument("--argocd", action="store_true", help="render Argo CD hooks and sync waves")
    a = ap.parse_args()
    k8s_out = a.k8s_out.resolve() if a.k8s_out else (ROOT / "deploy/k8s" if (ROOT / "deploy/k8s").is_dir() else None)
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    files = render(spec, k8s_out, a.argocd)
    stale = []
    for path, text in files.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if a.check and stale:
        print("out of date (run python3 tools/render_deploy.py):", *stale, sep="\n  ")
        return 1
    print(f"{len(files)} files, {len(stale)} updated" if not a.check else "deploy files are up to date")
    return 0


